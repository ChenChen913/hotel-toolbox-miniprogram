/**
 * 「数量归零」浮窗的共享口径（R4-4）。
 *
 * 为什么单独抽一个文件：
 *   两处会用到它 —— 向导第 ⑥ 步的确认清单、行程页的准备清单。
 *   文案与时长必须一致，而且「不超过 1 秒」是老板的硬要求，写成常量才好被测试盯住。
 *
 * 纯常量 + 纯函数，不碰 wx.*，可以直接在 vitest 里跑。
 */

/**
 * 浮窗显示时长（毫秒）。
 *
 * ⚠️ 这条值有过一次反转，历史留档（免得后人看到 1500 以为是随手写的）：
 *   · R4 时老板原话「显示的时间不要太长，大概在 1 秒以内，不得超过 1 秒」→ 定了 900。
 *   · R5（2026-10-02）老板改口「显示时间尽量稍微再加长一些」—— 两条要求互斥，
 *     明确授权由执行方定夺 → 定 1500。
 *
 * 为什么是 1500：最长文案「已记录到下方「已设为不带」，随时可恢复」18 个汉字，
 * 一眼读完约需 1.2s 完全不透明的时间；淡入占 0.22s（toast.wxss 的 transition），
 * 完全不透明从 0.22s 才开始 → 0.22 + 1.2 ≈ 1.42s，取整 1500ms（总在屏约 1.72s）。
 *
 * 为什么敢比「稍微」多加：.toast 有 pointer-events: none，不挡任何操作，
 * 停久的代价极低；太短则用户没读到，会误以为物品被删掉 —— 信息丢失不可逆。
 */
export const TOAST_MS = 1500;

/** 数量减到 0（= 不带）时的提示文案。与底部「已设为不带」区域的标题用词保持一致 */
export const TOAST_ZERO_TEXT = '已记录到下方「已设为不带」，随时可恢复';

/**
 * 该不该弹「归零」浮窗。
 *
 * 只在**从「有」变成「没有」的那一刻**弹：
 *   · 反复在 0 附近拨动（0→1→0）每次都会弹 —— 因为每次都是真的「刚归零」
 *   · 停在 0 上再点减号（stepper 已禁用，理论上到不了）不该弹
 *   · 从 0 恢复成 1 不弹（那不是归零）
 */
export function shouldToastZero(before: number, after: number): boolean {
  return Number.isFinite(before) && Number.isFinite(after) && before > 0 && after === 0;
}
