/** 按物品名称猜分类；命中不了返回 null（保持当前选择，不影响已有数据） */
export function guessGearCat(name: string): string | null {
  const n = name.trim().toLowerCase();
  if (!n) return null;
  let best: string | null = null;
  let bestLen = 0;
  for (const cat of CAT_ORDER) {
    if (cat === '自定义') continue;
    for (const k of GEAR_KEYWORDS[cat] ?? []) {
      if (!n.includes(k.toLowerCase())) continue;
      // 更长 = 更具体；同长时按 GEAR_TIE_BREAK 的顺序取胜
      const better = k.length > bestLen
        || (k.length === bestLen && best !== null
            && GEAR_TIE_BREAK.indexOf(cat) < GEAR_TIE_BREAK.indexOf(best));
      if (better) { best = cat; bestLen = k.length; }
    }
  }
  return best;
}

